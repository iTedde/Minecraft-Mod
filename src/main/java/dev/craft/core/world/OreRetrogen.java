/**
 * Places the Craft ores into chunks that were generated before they existed. Every chunk carries a retrogen version;
 * newly generated chunks get the current one, older chunks are decorated once with the ore features of their biomes
 * when they are loaded together with their eight neighbours (veins may cross the chunk border). Chunks that already
 * contain a Craft ore were generated by a version with the ores and are only marked. Copper is left out: old chunks
 * already have the vanilla copper that the Craft copper replaces.
 */
@EventBusSubscriber(modid = Craft.MODID)
public final class OreRetrogen {
    /** Raise when ore features are added so that existing chunks receive them. */
    private static final int VERSION = 1;
    private static final int CHUNKS_PER_TICK = 8;
    private static final int RESEND_INTERVAL = 10;
    private static final List<ResourceKey<PlacedFeature>> FEATURES = List.of(CraftWorldGen.ORE_TIN,
            CraftWorldGen.ORE_URANIUM, CraftWorldGen.GT_GALENA, CraftWorldGen.GT_IRIDIUM, CraftWorldGen.GT_RUBY,
            CraftWorldGen.GT_SAPPHIRE, CraftWorldGen.GT_BAUXITE, CraftWorldGen.GT_NETHER_ORES,
            CraftWorldGen.GT_END_ORES);
    private static final GenerationStep.Decoration STEP = GenerationStep.Decoration.UNDERGROUND_ORES;
    private static final Set<Heightmap.Types> WORLDGEN_HEIGHTMAPS =
            EnumSet.of(Heightmap.Types.OCEAN_FLOOR_WG, Heightmap.Types.WORLD_SURFACE_WG);

    public static final DeferredRegister<AttachmentType<?>> ATTACHMENT_TYPES =
            DeferredRegister.create(NeoForgeRegistries.ATTACHMENT_TYPES, Craft.MODID);

    private static final Supplier<AttachmentType<Integer>> RETROGEN_VERSION = ATTACHMENT_TYPES.register(
            "retrogen_version", () -> AttachmentType.builder(() -> 0).serialize(Codec.INT).build());

    private static final Map<ServerLevel, LevelState> STATES = new IdentityHashMap<>();

    private OreRetrogen() {
    }

    private static final class LevelState {
        final LongLinkedOpenHashSet pending = new LongLinkedOpenHashSet();
        final LongSet fresh = new LongOpenHashSet();
        final LongSet resend = new LongOpenHashSet();
    }

    @SubscribeEvent
    public static void onChunkLoad(ChunkEvent.Load event) {
        if (!(event.getLevel() instanceof ServerLevel level) || !(event.getChunk() instanceof LevelChunk chunk)
                || chunk.getData(RETROGEN_VERSION) >= VERSION) {
            return;
        }
        // The chunk is only queued here; it is touched on the server thread in the level tick.
        synchronized (STATES) {
            LevelState state = STATES.computeIfAbsent(level, l -> new LevelState());
            long pos = chunk.getPos().toLong();
            state.pending.add(pos);
            if (event.isNewChunk()) {
                state.fresh.add(pos);
            }
        }
    }

    @SubscribeEvent
    public static void onLevelUnload(LevelEvent.Unload event) {
        synchronized (STATES) {
            STATES.remove(event.getLevel());
        }
    }

    @SubscribeEvent
    public static void onLevelTick(LevelTickEvent.Post event) {
        if (!(event.getLevel() instanceof ServerLevel level)) {
            return;
        }
        synchronized (STATES) {
            LevelState state = STATES.get(level);
            if (state != null) {
                tick(level, state);
            }
        }
    }

    private static void tick(ServerLevel level, LevelState state) {
        int done = 0;
        for (int i = state.pending.size(); i > 0 && done < CHUNKS_PER_TICK; i--) {
            long pos = state.pending.removeFirstLong();
            boolean fresh = state.fresh.remove(pos);
            LevelChunk chunk = level.getChunkSource().getChunkNow(ChunkPos.getX(pos), ChunkPos.getZ(pos));
            if (chunk == null || chunk.getData(RETROGEN_VERSION) >= VERSION) {
                // Unloaded chunks are queued again on their next load.
                continue;
            }
            if (fresh || containsCraftOre(chunk)) {
                markDone(chunk);
                continue;
            }
            if (!neighboursLoaded(level, chunk.getPos())) {
                state.pending.add(pos);
                continue;
            }
            retrogen(level, chunk, state);
            done++;
        }
        if (!state.resend.isEmpty() && level.getGameTime() % RESEND_INTERVAL == 0) {
            resend(level, state.resend);
            state.resend.clear();
        }
    }

    private static boolean containsCraftOre(LevelChunk chunk) {
        for (LevelChunkSection section : chunk.getSections()) {
            if (!section.hasOnlyAir() && section.getStates().maybeHas(OreRetrogen::isCraftOre)) {
                return true;
            }
        }
        return false;
    }

    private static boolean isCraftOre(BlockState state) {
        return state.is(Tags.Blocks.ORES)
                && BuiltInRegistries.BLOCK.getKey(state.getBlock()).getNamespace().equals(Craft.MODID);
    }

    private static boolean neighboursLoaded(ServerLevel level, ChunkPos pos) {
        for (int dx = -1; dx <= 1; dx++) {
            for (int dz = -1; dz <= 1; dz++) {
                if (level.getChunkSource().getChunkNow(pos.x + dx, pos.z + dz) == null) {
                    return false;
                }
            }
        }
        return true;
    }

    private static void retrogen(ServerLevel level, LevelChunk chunk, LevelState state) {
        ChunkPos pos = chunk.getPos();
        ChunkGenerator generator = level.getChunkSource().getGenerator();
        Set<Holder<Biome>> biomes = new LinkedHashSet<>();
        for (LevelChunkSection section : chunk.getSections()) {
            section.getBiomes().getAll(biomes::add);
        }
        Set<ResourceKey<PlacedFeature>> present = new HashSet<>();
        for (Holder<Biome> biome : biomes) {
            List<HolderSet<PlacedFeature>> steps = generator.getBiomeGenerationSettings(biome).features();
            if (steps.size() <= STEP.ordinal()) {
                continue;
            }
            for (Holder<PlacedFeature> feature : steps.get(STEP.ordinal())) {
                feature.unwrapKey().filter(FEATURES::contains).ifPresent(present::add);
            }
        }
        if (!present.isEmpty()) {
            // Full chunks only keep the final heightmaps; the placements and features ask for the worldgen ones.
            for (int dx = -1; dx <= 1; dx++) {
                for (int dz = -1; dz <= 1; dz++) {
                    Heightmap.primeHeightmaps(level.getChunk(pos.x + dx, pos.z + dz), WORLDGEN_HEIGHTMAPS);
                }
            }
            WorldgenRandom random = new WorldgenRandom(new XoroshiroRandomSource(level.getSeed()));
            long seed = random.setDecorationSeed(level.getSeed(), pos.getMinBlockX(), pos.getMinBlockZ());
            BlockPos origin = new BlockPos(pos.getMinBlockX(), level.getMinBuildHeight(), pos.getMinBlockZ());
            Registry<PlacedFeature> registry = level.registryAccess().registryOrThrow(Registries.PLACED_FEATURE);
            for (int i = 0; i < FEATURES.size(); i++) {
                ResourceKey<PlacedFeature> key = FEATURES.get(i);
                if (!present.contains(key)) {
                    continue;
                }
                random.setFeatureSeed(seed, i, STEP.ordinal());
                registry.getOptional(key).ifPresent(feature -> feature.placeWithBiomeCheck(level, generator, random,
                        origin));
            }
        }
        markDone(chunk);
        // Ore features write into the block sections directly, so the touched chunks have to be saved and resent.
        List<ChunkPos> touched = new ArrayList<>(9);
        for (int dx = -1; dx <= 1; dx++) {
            for (int dz = -1; dz <= 1; dz++) {
                touched.add(new ChunkPos(pos.x + dx, pos.z + dz));
            }
        }
        for (ChunkPos neighbour : touched) {
            LevelChunk other = level.getChunkSource().getChunkNow(neighbour.x, neighbour.z);
            if (other != null) {
                other.setUnsaved(true);
                state.resend.add(neighbour.toLong());
            }
        }
    }

    private static void markDone(LevelChunk chunk) {
        chunk.setData(RETROGEN_VERSION, VERSION);
        chunk.setUnsaved(true);
    }

    private static void resend(ServerLevel level, LongSet positions) {
        positions.forEach((long pos) -> {
            LevelChunk chunk = level.getChunkSource().getChunkNow(ChunkPos.getX(pos), ChunkPos.getZ(pos));
            if (chunk == null) {
                return;
            }
            List<ServerPlayer> players = level.getChunkSource().chunkMap.getPlayers(chunk.getPos(), false);
            if (players.isEmpty()) {
                return;
            }
            var packet = new ClientboundLevelChunkWithLightPacket(chunk, level.getLightEngine(), null, null);
            for (ServerPlayer player : players) {
                player.connection.send(packet);
            }
        });
    }
}
